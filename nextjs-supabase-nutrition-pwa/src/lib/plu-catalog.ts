const PLU_TO_FOOD: Record<string, string> = Object.fromEntries(
  groups.flatMap(([food, codes]) => codes.map(code => [code, food] as const)),
);

export function normalizePlu(input: string): { code: string; organic: boolean } | null {
  const digits = input.replace(/\D/g, '');
  if (!/^\d{4,5}$/.test(digits)) return null;
  if (digits.length === 5 && digits.startsWith('9')) {
    return { code: digits.slice(1), organic: true };
  }
  return { code: digits, organic: false };
}

export function lookupPlu(input: string) {
  const normalized = normalizePlu(input);
  if (!normalized) return null;
  const food = PLU_TO_FOOD[normalized.code];
  if (!food) return null;
  return { ...normalized, food };
}
